#!/usr/bin/env node
// Vendors the V2 contract ABIs from a `forge build` of 0xHedgeHood/hedgehood-options into packages/sdk/src/abi/.
// Usage: node scripts/vendor-abis.mjs <path to hedgehood-options/contracts/out> [git commit]
// Only the ABI (no bytecode, no metadata) is copied: the contract sources themselves are not part of this repo.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [outDir, commit = "unknown"] = process.argv.slice(2);
if (!outDir) {
  console.error("usage: vendor-abis.mjs <forge out dir> [commit]");
  process.exit(1);
}
const targets = [
  ["CashOptionMarketV2", "marketV2Abi", "cashOptionMarketV2.ts"],
  ["CashOptionOrderBookV2", "orderBookV2Abi", "cashOptionOrderBookV2.ts"],
];
const dest = new URL("../packages/sdk/src/abi/", import.meta.url).pathname;
for (const [name, exportName, file] of targets) {
  const artifact = JSON.parse(readFileSync(join(outDir, `${name}.sol`, `${name}.json`), "utf8"));
  const body = `// Generated by scripts/vendor-abis.mjs from 0xHedgeHood/hedgehood-options ${name}.sol (commit ${commit}).\n` +
    `// ABI only; do not edit by hand.\n` +
    `export const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  writeFileSync(join(dest, file), body);
  console.log(`wrote ${file} (${artifact.abi.length} entries)`);
}
