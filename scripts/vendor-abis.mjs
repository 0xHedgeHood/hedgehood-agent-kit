#!/usr/bin/env node
// Vendors contract ABIs from a `forge build` into packages/sdk/src/abi/. Only the ABI (no bytecode, no metadata) is
// copied: the contract sources themselves are not part of this repo.
//
//   node scripts/vendor-abis.mjs <hedgehood-options/contracts/out> [git commit]            # CashOptionMarketV2 + book
//   node scripts/vendor-abis.mjs --vaults <hedgehood-vaults/contracts/out> [git commit]    # EpochFund, VaultRegistry, gates
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const argv = process.argv.slice(2);
const vaults = argv[0] === "--vaults";
const [outDir, commit = "unknown"] = vaults ? argv.slice(1) : argv;
if (!outDir) {
  console.error("usage: vendor-abis.mjs [--vaults] <forge out dir> [commit]");
  process.exit(1);
}
const sets = {
  market: {
    repo: "0xHedgeHood/hedgehood-options",
    targets: [
      ["CashOptionMarketV2", "marketV2Abi", "cashOptionMarketV2.ts"],
      ["CashOptionOrderBookV2", "orderBookV2Abi", "cashOptionOrderBookV2.ts"],
    ],
  },
  vaults: {
    repo: "0xHedgeHood/hedgehood-vaults",
    targets: [
      ["EpochFund", "epochFundAbi", "epochFund.ts"],
      ["VaultRegistry", "vaultRegistryAbi", "vaultRegistry.ts"],
      ["OpenDepositGate", "openDepositGateAbi", "openDepositGate.ts"],
      ["StakeThresholdGate", "stakeThresholdGateAbi", "stakeThresholdGate.ts"],
    ],
  },
};
const set = vaults ? sets.vaults : sets.market;
const dest = new URL("../packages/sdk/src/abi/", import.meta.url).pathname;
for (const [name, exportName, file] of set.targets) {
  const artifact = JSON.parse(readFileSync(join(outDir, `${name}.sol`, `${name}.json`), "utf8"));
  const body = `// Generated by scripts/vendor-abis.mjs from ${set.repo} ${name}.sol (commit ${commit}).\n` +
    `// ABI only; do not edit by hand.\n` +
    `export const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  writeFileSync(join(dest, file), body);
  console.log(`wrote ${file} (${artifact.abi.length} entries)`);
}
