#!/usr/bin/env node
// Vendors contract ABIs from a `forge build` into packages/sdk/src/abi/. Only the ABI (no bytecode, no metadata) is
// copied: the contract sources themselves are not part of this repo.
//
//   node scripts/vendor-abis.mjs <hedgehood-options/contracts/out> [git commit]            # CashOptionMarketV2, book, settlement source
//   node scripts/vendor-abis.mjs --vaults <hedgehood-vaults/contracts/out> [git commit]    # EpochFund, VaultRegistry, gates
//   node scripts/vendor-abis.mjs --testusd <hedgehood-options/contracts/out> [git commit]  # TestUSD, the testnet settlement token
//   node scripts/vendor-abis.mjs --lending <hedgehood-vaults root> [git commit]            # Share lending: Morpho Blue,
//        AdaptiveCurveIrm, ShareRiskOracle, Morpho Vault V2 + its Blue adapter. Blue and the IRM come from the committed
//        creation artifacts (contracts/script/artifacts), the oracle from `forge build` (contracts/out), Vault V2 from the
//        vendored upstream build (local/share-collateral-a/vendor/vault-v2/out, override with VAULT_V2_OUT).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const argv = process.argv.slice(2);
const mode = argv[0] === "--vaults" ? "vaults" : argv[0] === "--lending" ? "lending" : argv[0] === "--testusd" ? "testusd" : "market";
const [outDir, commit = "unknown"] = mode === "market" ? argv : argv.slice(1);
if (!outDir) {
  console.error("usage: vendor-abis.mjs [--vaults|--lending|--testusd] <forge out dir | repo root> [commit]");
  process.exit(1);
}
const vaultV2Out = process.env.VAULT_V2_OUT ?? join(outDir, "local/share-collateral-a/vendor/vault-v2/out");
/** [artifact path (relative to outDir unless absolute), export name, target file, provenance]. */
const sets = {
  market: {
    repo: "0xHedgeHood/hedgehood-options",
    targets: [
      ["CashOptionMarketV2.sol/CashOptionMarketV2.json", "marketV2Abi", "cashOptionMarketV2.ts", "CashOptionMarketV2.sol"],
      ["CashOptionOrderBookV2.sol/CashOptionOrderBookV2.json", "orderBookV2Abi", "cashOptionOrderBookV2.ts", "CashOptionOrderBookV2.sol"],
      ["ChainlinkExpirySource.sol/ChainlinkExpirySource.json", "chainlinkExpirySourceAbi", "chainlinkExpirySource.ts", "ChainlinkExpirySource.sol"],
    ],
  },
  testusd: {
    repo: "0xHedgeHood/hedgehood-options",
    targets: [["TestUSD.sol/TestUSD.json", "testUsdAbi", "testUsd.ts", "src/mocks/TestUSD.sol"]],
  },
  vaults: {
    repo: "0xHedgeHood/hedgehood-vaults",
    targets: [
      ["EpochFund.sol/EpochFund.json", "epochFundAbi", "epochFund.ts", "EpochFund.sol"],
      ["VaultRegistry.sol/VaultRegistry.json", "vaultRegistryAbi", "vaultRegistry.ts", "VaultRegistry.sol"],
      ["OpenDepositGate.sol/OpenDepositGate.json", "openDepositGateAbi", "openDepositGate.ts", "OpenDepositGate.sol"],
      ["StakeThresholdGate.sol/StakeThresholdGate.json", "stakeThresholdGateAbi", "stakeThresholdGate.ts", "StakeThresholdGate.sol"],
    ],
  },
  lending: {
    repo: "0xHedgeHood/hedgehood-vaults",
    targets: [
      ["contracts/script/artifacts/Morpho.json", "morphoBlueAbi", "morphoBlue.ts", "Morpho Blue core, morpho-org/morpho-blue 8e26ca6 (committed creation artifact contracts/script/artifacts/Morpho.json)"],
      ["contracts/script/artifacts/AdaptiveCurveIrm.json", "adaptiveCurveIrmAbi", "adaptiveCurveIrm.ts", "AdaptiveCurveIrm, morpho-org/morpho-blue-irm b9a5806 (committed creation artifact contracts/script/artifacts/AdaptiveCurveIrm.json)"],
      ["contracts/out/ShareRiskOracle.sol/ShareRiskOracle.json", "shareRiskOracleAbi", "shareRiskOracle.ts", "contracts/src/collateral/ShareRiskOracle.sol"],
      [join(vaultV2Out, "VaultV2.sol/VaultV2.json"), "vaultV2Abi", "vaultV2.ts", "Morpho Vault V2, morpho-org/vault-v2 10ed1ea src/VaultV2.sol (local/share-collateral-a/vault-v2/SOURCE.json)"],
      [join(vaultV2Out, "MorphoMarketV1AdapterV2.sol/MorphoMarketV1AdapterV2.json"), "morphoMarketV1AdapterV2Abi", "morphoMarketV1AdapterV2.ts", "morpho-org/vault-v2 10ed1ea src/adapters/MorphoMarketV1AdapterV2.sol"],
    ],
  },
};
const set = sets[mode];
const dest = new URL("../packages/sdk/src/abi/", import.meta.url).pathname;
for (const [rel, exportName, file, provenance] of set.targets) {
  const path = rel.startsWith("/") ? rel : join(outDir, rel);
  const artifact = JSON.parse(readFileSync(path, "utf8"));
  const body = `// Generated by scripts/vendor-abis.mjs from ${set.repo} ${provenance} (commit ${commit}).\n` +
    `// ABI only; do not edit by hand.\n` +
    `export const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  writeFileSync(join(dest, file), body);
  console.log(`wrote ${file} (${artifact.abi.length} entries)`);
}
